/*
 * The glow that follows the pointer along the card's border.
 *
 * The ring is a `::before` inset to the card's own box, filled with a radial gradient centred on
 * the two custom properties the page's pointer handler writes, then CUT DOWN TO ITS BORDER by
 * two masks composited with `exclude`: one clipped to the content box, one to the border box, so
 * what survives is the `padding` band between them. That is the standard border-gradient trick,
 * and the 1px padding is what makes the band a hairline.
 *
 * TRAP — `inherit` on the radius is load-bearing. A ring drawn at a different radius from the
 * box it hugs separates from the corners, and nothing in the console says so.
 *
 * Behind `hover: hover` and never `any-hover`, which is true as soon as ANY hovering pointer is
 * attached: on a touch screen the glow would light where the last tap landed and stay there.
 */
@media (hover: hover) {
