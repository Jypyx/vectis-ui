/*
 * The hero's glow — two pools of colour drifting out of the top of the page, so the first
 * screen is not one flat fill from edge to edge, and is not standing still either.
 *
 * It lives here rather than in docs-layout.css for the reason that file states about itself: a
 * pseudo-element and its keyframes belong to the one component that draws them, as the outline's
 * link states do. It hangs off <main>, which is a direct child of the flex column and so
 * spans the full width already — anchoring it on .vd-hero instead would stop the glow at the
 * 1440px content column and leave a vertical seam on a wider screen, and the usual
 * `calc(50% - 50vw)` bleed would then overflow by half a scrollbar.
 *
 * ONE POOL PER PSEUDO-ELEMENT, and that is the whole shape of the thing. The two pools used to
 * be two background layers on a single ::before, which is fine while nothing moves: the only
 * way to shift two layers of one background independently is `background-position`, and that
 * REPAINTS a full-width surface on every frame. Split across ::before and ::after, each pool
 * animates in `translate`, `scale` and `opacity` — the three properties the compositor takes
 * off the main thread, the argument VSkeletonLoader already writes for its wave.
 *
 * The split is also what removed the mask. Each pool is now a self-contained ellipse whose
 * gradient dies out in EVERY direction (`closest-side` … `transparent`), so there is no edge
 * anywhere for the movement to reveal. A masked full-width band would have shown its own top
 * edge the moment it drifted down, which is exactly what it is asked to do here.
 *
 * The colours are RELATIVE to the accent role (`oklch(from …)`, the VSkeletonLoader idiom):
 * this site repoints that role to violet, and the second pool sits 45 degrees round the hue
 * circle from wherever it lands. Repointing the accent repaints the glow, with no hue written
 * as a number and no second place to keep in step.
 */
/*
 * Two rules for content the catalogue renders as raw HTML: it carries no scope attribute, so
 * `:deep` is what reaches it — a plain scoped selector matches nothing there, and fails
 * silently. The `<code>` run inside a sentence is the one piece of type on this page that
 * VTypography cannot carry, being inside an `innerHTML` rather than a slot.
 */
