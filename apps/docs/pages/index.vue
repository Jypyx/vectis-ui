  }
  50% {
    translate: -1% 27%;
  }
  62.5% {
    translate: -9% 24%;
  }
  75% {
    translate: -10% 15%;
  }
  87.5% {
    translate: -5% 7%;
  }
}
@keyframes vd-glow-drift-b {
