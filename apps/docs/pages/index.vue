/*
 * TRAP — 0% and 100% must stay IDENTICAL in all six. That equality is the whole of the seamless
 * loop: an iteration ends exactly where the next one starts, so there is no frame at which the
 * pool jumps back. Change one end without the other and the glow snaps, once per period, at a
 * distance no easing can hide.
 *
 * Travel, size and intensity are three separate animations on purpose. They touch disjoint
 * properties — `translate`, `scale`, `opacity` — so they compose rather than fight, and each
 * pool's three periods are coprime (15/11/8 and 11/9/7 seconds), which is what stops them from
 * re-syncing into a recognisable beat. One animation per pool would replay the same gesture on
 * the dot every 15 seconds, and it would also force the travel to share the breath's easing.
 *
 * TRAP — the eight legs of a drift must stay ROUGHLY EQUAL IN LENGTH, since `linear` divides
 * the time between them equally. A leg twice its neighbour's length is travelled at twice the
 * speed, which brings back by the back door exactly the fast/slow reading the linear rate was
 * chosen to remove. Both paths below hold to within about 5%.
 *
 * A `translate` percentage resolves against the element's OWN box, so the 27% below is 27% of
 * 70vh — close to 19vh of travel down over the hero, which is where the glow is meant to reach.
 */
