   * The pools' INTENSITY is the one thing the theme owns, and it has to: the recipe below
   * replaces the accent's lightness and chroma outright, so both themes paint the same ink —
   * what changes is the paper. The same translucent violet that reads clearly over a near
   * black surface barely tints a white one, so light takes a darker, more saturated pool to
   * arrive at the same visible strength, and dark takes a brighter one it can afford. Only
   * the hue is still read off the accent, which is what keeps a repointed accent repainting
   * the glow with no number written twice.
   */
  --vd-glow-l: 56%;
  --vd-glow-c: 0.26;
  --vd-glow-a1: 0.34;
  --vd-glow-a2: 0.26;
}
[data-theme='dark'] .vd-home {
  --vd-glow-l: 66%;
  --vd-glow-c: 0.27;
  --vd-glow-a1: 0.42;
  --vd-glow-a2: 0.32;
}
/*
 * What the two pools share. Sizes and colours are per-pool below, and so is every animation
 * NAME and DURATION — only the shape of the motion is common.
 *
 * `--vectis-ease-in-out` is the token whose own description names looping animations that cross
 * a track: symmetric, so the pool eases out of one keyframe and into the next at the same rate,
 * which reads as a breath rather than a shuttle.
 *
 * No `will-change`. An element with a running `translate`/`scale`/`opacity` animation is already
 * promoted to its own layer by the engine; declaring it permanently would hold that memory for
 * two surfaces this size and buy nothing.
 */
.vd-home::before,
.vd-home::after {
  content: '';
  position: absolute;
  z-index: -1;
  pointer-events: none;
  /* Each pool fades to nothing well inside its own box, in every direction — which is what
     makes it safe to move. Nothing here has an edge to reveal. */
  background: radial-gradient(closest-side, var(--vd-pool), transparent);
  /*
   * Positional, and it lines up with the `animation-name` list each pool declares below: DRIFT,
   * then swell, then pulse. Both pools order them the same way, which is what lets the list be
   * written once here instead of twice down there.
   *
   * The drift is `linear` and must stay so. Eased, a pool accelerates out of every keyframe and
   * coasts into the next — the same journey read as fast, slow, fast, which is what a wandering
   * glow must never do. A constant rate over eight roughly equal legs is what makes the path
   * continuous instead. Easing is right for the other two, where nothing travels: swelling and
   * brightening are supposed to breathe.
   */
  animation-timing-function: linear, var(--vectis-ease-in-out), var(--vectis-ease-in-out);
  animation-iteration-count: infinite;
}

/*
 * Two off-centre pools rather than one centred: a single one reads as a vignette, and this pair
 * leaves the middle of the headline on the flat surface. They overlap across the top of the
