/**
 * Where the hover glow sits, and the only JavaScript on this page: a pointer position is the
 * one thing CSS cannot read on its own.
 *
 * BOUND PER CARD, not delegated to the grid, and that is forced rather than chosen:
 * `pointerleave` does NOT bubble, so a listener on the container would only ever fire when the
 * pointer left the whole grid — the glow would keep its last position while crossing from one
 * card to its neighbour. Per card, `currentTarget` is always the card itself, which also
 * removes the `closest()` a delegated handler would have needed to turn an event fired on an
 * icon or a heading into the box it belongs to.
 *
 * The write goes through `setProperty` rather than a reactive `:style`, deliberately: a binding
 * would re-render the grid on every frame of a pointer move, for two decorative custom
 * properties nothing else reads.
 *
 * Clearing on leave is not tidiness. The glow is revealed by `:hover`, so leaving the values
 * behind would light it at the point the pointer LEFT for the frame or two before the first
 * move event of the next entry arrives.
 */
function onCardPointerMove(event: PointerEvent) {
  const card = event.currentTarget as HTMLElement
  const rect = card.getBoundingClientRect()
  card.style.setProperty('--vd-card-x', `${event.clientX - rect.left}px`)
  card.style.setProperty('--vd-card-y', `${event.clientY - rect.top}px`)
}

function onCardPointerLeave(event: PointerEvent) {
  const card = event.currentTarget as HTMLElement
  card.style.removeProperty('--vd-card-x')
  card.style.removeProperty('--vd-card-y')
}

