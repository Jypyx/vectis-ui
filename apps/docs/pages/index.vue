}
.vd-home :deep(code) {
  font-family: var(--vectis-text-family-code);
  font-size: var(--vectis-text-code-size);
}

/*
 * The feature cards, written once because the six are a loop.
 *
 * THREE LAYERS, and the order of the two written here is the whole of the effect. On top, a
 * wash of the card's own hue thrown from the TOP-LEFT corner and gone by the middle of the box;
 * under it, the raised surface. A background colour is always the BOTTOM layer of a `background`
 * shorthand whatever its position in the list, so the two cannot be written the other way round
 * by accident. The third layer is the ::before hairline further down, which is the same hue
 * again at hover strength.
 *
 * The surface is a MIX towards transparent rather than the flat raised token — the header bar's
 * idiom — which is what lets the hero's glow wash under the top row instead of stopping at it.
 * Both themes take the same recipe: `surface-raised` already flips, so the card is a shade above
 * the page in light and a shade above the near-black in dark, with one declaration. The wash is
 * translucent for the same reason, so it tints what passes through rather than shutting it out.
 *
 * The wash is an ELLIPSE `at 0% 0%` and not a linear gradient down the diagonal: a linear one
 * has a direction but no origin, so its colour would run the full length of the top-right and
 * bottom-left edges instead of pooling in the one corner. `140% 110%` is measured against the
 * card's own box, so a tall card and a short one hold the same shape of pool.
 */
.vd-home-card {
  /*
   * What a hue is worth, and the only place the six colours are given a strength. Dark restates
   * all five in the rule immediately below; there is no third theme.
   *
   * The wash and the hairline are tuned apart because they answer to different things. The wash
   * is a tint on a surface with the card's own copy sitting on it, so it SWAPS DIRECTION between
   * the themes: over near-white it has to be darker than the paper to register at all, over
   * near-black lighter than it. The hairline has nothing reading through it, so it takes the
   * vivid end of the same hue and only rises in dark, where a mid-lightness stroke would sink
   * into the border it is replacing.
   *
   * The alpha is the HIGHER of the two in dark, which reads backwards and is not: what limits it
   * is the muted body text that sits on the corner, and dark starts that pairing near 10:1 where
   * light starts it near 7:1. The tint costs almost nothing at either end — the corner measures
   * 9.6:1 in dark and 6.4:1 in light at the values below, so both stay clear of AA — but light
   * is the theme with less to spend, and it is the one to re-measure if this table moves.
   */
  --vd-wash-l: 58%;
  --vd-wash-c: 0.15;
  --vd-wash-a: 0.13;
  --vd-line-l: 58%;
  --vd-line-c: 0.19;

  position: relative;
  padding: var(--vectis-space-6);
  border: 1px solid var(--vectis-color-border);
  border-radius: var(--vectis-radius-surface);
  background:
    radial-gradient(
      140% 110% at 0% 0%,
      oklch(var(--vd-wash-l) var(--vd-wash-c) var(--vd-card-hue) / var(--vd-wash-a)),
      transparent 62%
    ),
    color-mix(in oklch, var(--vectis-color-surface-raised) 72%, transparent);
}
