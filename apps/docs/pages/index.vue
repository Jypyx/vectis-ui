      oklch(var(--vd-line-l) var(--vd-line-c) var(--vd-card-hue)),
      transparent 70%
    );
    mask:
      linear-gradient(black, black) content-box,
      linear-gradient(black, black);
    mask-composite: exclude;
    opacity: 0;
    transition: opacity var(--vectis-duration-base) var(--vectis-ease-out);
    pointer-events: none;
  }
  .vd-home-card:hover::before {
    opacity: 1;
  }

  /* The fade goes, the tracking stays: a glow that interpolated towards the pointer would not
     follow it, it would chase it. */
  @media (prefers-reduced-motion: reduce) {
    .vd-home-card::before {
      transition: none;
    }
  }
}

.vd-home {
  position: relative;
  /*
   * The glow paints at z-index -1 — above the shell's flat background, below the copy, so no
   * text contrast is measured against it. The stacking context is what confines that -1:
   * without it the glow would slide behind .vd-shell's own background and simply not appear,
   * with nothing in the console to say why.
   */
  isolation: isolate;

  /*
   * TRAP — the axis matters, in both directions. The pools sit on negative inline insets and
   * drift further sideways still, and overflow past the END of the line is what mints a
   * horizontal scrollbar on the whole document. `clip` on the inline axis alone is the fix:
   * `clip` is the ONE value that may pair with `visible` (any other would force the other axis
   * to `auto`), so the box does not become a scroll container, and the block axis stays
   * unclipped — which is what preserves the pools' bleed ABOVE this element, the whole reason
   * the glow shows through the header. Written `overflow: clip`, it would cut the glow off flat
   * under the bar.
   */
  overflow-x: clip;

