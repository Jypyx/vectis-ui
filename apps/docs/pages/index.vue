 * One number per card: an OKLCH hue angle, chosen for the subject rather than derived from
 * anything. The lightness, chroma and alpha that turn a hue into the two paints — the corner
 * wash and the hover hairline — are the THEME's: the five properties on `.vd-home-card` itself,
 * restated by the dark rule beside it. That is what keeps the six at one strength — a card can
